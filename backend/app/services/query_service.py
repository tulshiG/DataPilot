# Summary builder
# ---------------------------------------------------------------------------

def _build_summary(
    intent: str, rows: list[dict], columns: list[str],
    raw_query: str = "", spec: dict = None
) -> str:
    """Build an intelligent human-readable summary for query results."""
    spec = spec or {}

    if not rows:
        return "No results were found for this query."

    # Single aggregate value
    if intent == "aggregate" and len(rows) == 1 and "value" in columns:
        val = rows[0]["value"]
        formatted_val = _format_value(val)
        query_lower = raw_query.lower()

        if "average" in query_lower or "avg" in query_lower:
            return f"The average is {formatted_val}."
        if "count" in query_lower or "how many" in query_lower or "number of" in query_lower:
            return f"There are {formatted_val} total records."
        if "revenue" in query_lower or "sales" in query_lower:
            return f"The total revenue is {formatted_val}."
        if "total" in query_lower:
            return f"The total is {formatted_val}."
        return f"The result is {formatted_val}."

    # Grouped aggregate results
    if "group_value" in columns and "value" in columns:
        if intent in ("top_n", "bottom_n"):
            label = "top" if intent == "top_n" else "bottom"
            return f"Found {len(rows)} {label} result(s), ranked by value."

        # City/category comparison
        query_lower = raw_query.lower()
        if "city" in query_lower or "compare" in query_lower:
            top = rows[0] if rows else {}
            top_val = _format_value(top.get("value", ""))
            top_grp = top.get("group_value", "")
            return (
                f"Results grouped by dimension — "
                f"{top_grp} leads with {top_val}. "
                f"Showing {len(rows)} group(s)."
            )

        return f"Results grouped into {len(rows)} categories."

    # Date-trunc trend results
    if "period" in columns and "value" in columns:
        return f"Showing {len(rows)} time period(s) of data."

    # Top N results
    if intent in ("top_n", "bottom_n"):
        return f"Found {len(rows)} result(s), ranked as requested."

    # List results
    return f"Found {len(rows)} matching row(s)."


def _format_value(val) -> str:
    """Format a numeric or string value nicely."""
    if isinstance(val, float):
        if val == int(val):
            return f"{int(val):,}"
        return f"{val:,.2f}"
    if isinstance(val, int):
        return f"{val:,}"
    return str(val)