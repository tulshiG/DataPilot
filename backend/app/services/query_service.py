from sqlalchemy.orm import Session
from sqlalchemy import create_engine, text, inspect as sa_inspect

from app.knowledge_engine.forward_chaining import resolve_query_chain
from app.nlp_engine.sql_generator import generate_sql
from app.services.history_service import log_query
from app.core.config import settings
from app.core.exceptions import BadRequestException


def run_natural_language_query(
    db: Session, workspace_id: int, user_id: int,
    raw_query: str, dataset_id: int | None = None
) -> dict:
    """
    Main entry point for natural language queries.
    Handles both SQL-based queries and special meta-intents
    (dashboard, business insights, never-sold, etc.).
    """
    chain_result = resolve_query_chain(db, workspace_id, raw_query, dataset_id)
    spec = chain_result["query_spec"]
    intent = chain_result["intent"]["intent"]
    intent_result = chain_result["intent"]

    if spec.get("needs_clarification"):
        return {
            "needs_clarification": True,
            "message": spec.get("clarification_reason", "Please clarify your request."),
            "candidates": spec.get("dataset_candidates", []),
            "raw_query": raw_query,
            "intent": intent,
        }

    # ------------------------------------------------------------------
    # Route special meta-intents
    # ------------------------------------------------------------------
    if intent_result.get("is_special"):
        return _handle_special_intent(db, workspace_id, user_id, raw_query, intent, chain_result)

    sql = None
    try:
        # Prefer the SQL generated by the pipeline directly, fallback to old function call
        sql = chain_result.get("generated_sql")
        params = chain_result.get("sql_params", {})
        if not sql:
            sql, params = generate_sql(spec)

        # Handle never_sold gracefully — try to auto-resolve schema
        if spec.get("special_query") == "never_sold":
            return _handle_never_sold(db, workspace_id, user_id, raw_query, spec, chain_result)

        engine = create_engine(settings.DATABASE_URL)
        try:
            with engine.connect() as conn:
                result = conn.execute(text(sql), params)
                columns = list(result.keys())
                rows = [dict(zip(columns, row)) for row in result.fetchall()]
        finally:
            engine.dispose()

        summary = _build_summary(intent, rows, columns, raw_query, spec)

        log_query(
            db, workspace_id, user_id, raw_query,
            intent=intent, sql=sql, spec=spec,
            status="success", row_count=len(rows),
        )

        return {
            "raw_query": raw_query,
            "intent": intent,
            "matched_rule": chain_result["matched_rule"],
            "generated_sql": sql,
            "columns": columns,
            "rows": rows,
            "row_count": len(rows),
            "summary": summary,
        }

    except Exception as e:
        log_query(
            db, workspace_id, user_id, raw_query,
            intent=intent, sql=sql, spec=spec,
            status="failed", error_message=str(e),
        )
        raise BadRequestException(f"Could not process query: {str(e)}")


# ---------------------------------------------------------------------------
# Special intent handlers
# ---------------------------------------------------------------------------

def _handle_special_intent(
    db: Session, workspace_id: int, user_id: int,
    raw_query: str, intent: str, chain_result: dict
) -> dict:
    """Route special meta-intents to their dedicated engines."""
    try:
        if intent == "generate_dashboard":
            return _handle_dashboard_intent(db, workspace_id, user_id, raw_query, chain_result)
        elif intent == "generate_insights":
            return _handle_insights_intent(db, workspace_id, user_id, raw_query, chain_result)
        elif intent == "never_sold":
            spec = chain_result["query_spec"]
            return _handle_never_sold(db, workspace_id, user_id, raw_query, spec, chain_result)
        else:
            raise BadRequestException(f"Unknown special intent: {intent}")
    except BadRequestException:
        raise
    except Exception as e:
        raise BadRequestException(f"Could not process special query: {str(e)}")


def _handle_dashboard_intent(
    db: Session, workspace_id: int, user_id: int,
    raw_query: str, chain_result: dict
) -> dict:
    """Generate a full sales dashboard via the visualization engine."""
    from app.visualization_engine.dashboard_generator import generate_dashboard
    dashboard_data = generate_dashboard(db, workspace_id, {})

    log_query(
        db, workspace_id, user_id, raw_query,
        intent="generate_dashboard", sql=None, spec={},
        status="success", row_count=0,
    )

    return {
        "raw_query": raw_query,
        "intent": "generate_dashboard",
        "matched_rule": chain_result.get("matched_rule"),
        "generated_sql": None,
        "columns": ["dashboard"],
        "rows": [{"dashboard": dashboard_data}],
        "row_count": 1,
        "summary": "Sales dashboard has been generated with KPIs, revenue trends, top products, and customer analysis.",
        "dashboard": dashboard_data,
    }


